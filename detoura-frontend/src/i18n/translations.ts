/**
 * Formats daily price consistently across languages (e.g. ₹2,500 / day, ₹2,500 / दिन, ₹2,500 / দিন).
 */
export function formatPricePerDay(amount: number | string | undefined, lang: Language): string {
  const num = Math.round(Number(amount || 0));
  const formatted = num.toLocaleString('en-IN');
  const perDay = translate(lang, 'common.perDay');
  return `₹${formatted}${perDay}`;
}

/**
 * Formats duration consistently across languages (e.g. 2 Days, 2 दिन, 2 দিন).
 */
export function formatDuration(days: number | string | undefined, lang: Language): string {
  const d = Number(days || 1);
  if (lang === 'bn') {
    return `${d} দিন`;
  }
  if (lang === 'hi') {
    return `${d} दिन`;
  }
  return `${d} ${d === 1 ? 'Day' : 'Days'}`;
}

/**
 * Formats destination address consistently across languages without English mixing.
 */
export function formatAddress(
  name: string | undefined,
  district: string | undefined,
  _rawAddress: string | undefined,
  lang: Language
): string {
  const locName = localizeDestinationName(name, lang);
  const locDist = localizeRegion(district, lang);
  const locState = translate(lang, 'regions.westBengal');

  if (locName && locDist) {
    return `${locName}, ${locDist}, ${locState}`;
  }
  if (locDist) {
    return `${locDist}, ${locState}`;
  }
  return locState;
}

/**
 * Formats destination summary description cleanly across EN, HI, and BN without language mixing.
 */
export function formatDestinationDescription(
  rec: { name?: string; district?: string; description?: string },
  lang: Language
): string {
  const locName = localizeDestinationName(rec.name, lang);
  const locDist = localizeRegion(rec.district, lang);
  let desc = (rec.description || '').trim();

  // If description contains raw English name or district, substitute them
  if (rec.name && locName && locName !== rec.name && desc.includes(rec.name)) {
    desc = desc.split(rec.name).join(locName);
  }
  if (rec.district && locDist && locDist !== rec.district && desc.includes(rec.district)) {
    desc = desc.split(rec.district).join(locDist);
  }

  if (lang === 'bn') {
    const stripped = desc.replace(/\b(DETOURA|SSI|INR|GPS|CPI|km)\b/gi, '').trim();
    if (/[\u0980-\u09FF]/.test(desc) && !/\b[a-z]{3,}\b/i.test(stripped)) {
      return desc;
    }
    return `${locDist}-এর ${locName} কম ভিড় এবং উচ্চ প্রশান্তি সহ একটি মনোরম অফবিট গন্তব্য।`;
  }
  if (lang === 'hi') {
    const stripped = desc.replace(/\b(DETOURA|SSI|INR|GPS|CPI|km)\b/gi, '').trim();
    if (/[\u0900-\u097F]/.test(desc) && !/\b[a-z]{3,}\b/i.test(stripped)) {
      return desc;
    }
    return `${locDist} स्थित ${locName} कम भीड़ और उच्च प्राकृतिक सुंदरता वाला एक शांत ऑफबीट गंतव्य है।`;
  }
  if (!/[\u0900-\u097F\u0980-\u09FF]/.test(desc) && desc) {
    return desc;
  }
  return `${locName} in ${locDist} offers a calibrated offbeat detour with high scenic value and low crowd congestion.`;
}

